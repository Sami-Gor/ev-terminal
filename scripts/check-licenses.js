#!/usr/bin/env node
'use strict';

/**
 * check-licenses.js — audits every installed package (dependencies and
 * transitive dependencies) against a permissive license allowlist and
 * regenerates THIRD_PARTY_NOTICES.md. Exits 1 on any non-permissive license.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ALLOWED = new Set([
  'MIT', 'MIT*', '(MIT OR Apache-2.0)', '(MIT OR CC0-1.0)',
  'Apache-2.0', 'Apache 2.0', '(Apache-2.0 OR MIT)',
  'ISC', '0BSD', 'BSD-2-Clause', 'BSD-3-Clause', 'BSD',
  'CC-BY-3.0', 'CC-BY-4.0', 'Unlicense', 'WTFPL',
  '(WTFPL OR MIT)', '(MIT OR WTFPL)',
]);

function walkModules(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.name === 'node_modules') {           // nested dep
      walkModules(full, out);
      continue;
    }
    const pkgFile = path.join(full, 'package.json');
    if (fs.existsSync(pkgFile)) {
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
        out.set(pkg.name || entry.name, {
          name: pkg.name || entry.name,
          version: pkg.version || '?',
          license: pkg.license || 'UNKNOWN',
          homepage: pkg.homepage || (pkg.repository && (pkg.repository.url || pkg.repository)) || '',
          path: full,
        });
      } catch (e) { /* unreadable package.json — ignore */ }
    }
    const nested = path.join(full, 'node_modules');
    if (fs.existsSync(nested)) walkModules(nested, out);
  }
}

function main() {
  const nodeModules = path.join(ROOT, 'node_modules');
  if (!fs.existsSync(nodeModules)) {
    console.error('node_modules not found — run `npm install` first.');
    process.exit(1);
  }
  const packages = new Map();
  walkModules(nodeModules, packages);

  const rows = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
  const bad = rows.filter(p => !ALLOWED.has(p.license));

  if (bad.length) {
    console.error('NON-PERMISSIVE LICENSES FOUND:');
    for (const p of bad) console.error(`  ${p.name}@${p.version} — ${p.license}`);
    process.exit(1);
  }

  let md = '# Third-Party Notices\n\n';
  md += 'Generated by `npm run check:licenses` — do not edit by hand.\n\n';
  md += `This project is distributed under the [MIT License](LICENSE) and depends on the ` +
        `following ${rows.length} open-source packages (including transitive dependencies), ` +
        `all under permissive licenses (MIT / Apache-2.0 / BSD / ISC):\n\n`;
  md += '| Package | Version | License |\n|---|---|---|\n';
  for (const p of rows) md += `| [${p.name}](${p.homepage || '#'}) | ${p.version} | ${p.license} |\n`;
  md += '\nEach package remains under its own license terms; the table above is provided for attribution.\n';
  fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), md);

  console.log(`license audit: ${rows.length} packages, 0 non-permissive — OK`);
  console.log('THIRD_PARTY_NOTICES.md regenerated');
}

main();
